void VideoProcessor::DrawChar(uint8_t* pY, uint32_t stride, uint32_t x, uint32_t y, char c, uint8_t luma)
{
    if (c >= 'a' && c <= 'z') c = static_cast<char>(c - 32); // uppercase
    if (c < ' ' || c > 'Z') c = ' ';

    int fontIdx = c - ' ';
    const uint8_t* rows = FONT_5X7[fontIdx];

    // Scale 2x for readability on 1080p
    const int scale = 2;
    for (int r = 0; r < 7; r++) {
        uint8_t rowBits = rows[r];
        for (int col = 0; col < 5; col++) {
            if (rowBits & (1 << (4 - col))) {
                for (int dy = 0; dy < scale; dy++) {
                    for (int dx = 0; dx < scale; dx++) {
                        pY[(y + r * scale + dy) * stride + (x + col * scale + dx)] = luma;
                    }
                }
            }
        }
    }
}

void VideoProcessor::DrawString(uint8_t* pY, uint32_t stride, uint32_t x, uint32_t y, const char* str, uint8_t luma)
{
    const int charWidth = 14; // 5 * 2 + 4 spacing
    while (*str) {
        DrawChar(pY, stride, x, y, *str, luma);
        x += charWidth;
        str++;
    }
}

void VideoProcessor::GenerateIdleSlate(uint8_t* pNv12, uint32_t width, uint32_t height)
{
    // Dark professional slate (Y=24 dark gray, UV=128 neutral gray)
    uint32_t ySize = width * height;
    memset(pNv12, 24, ySize);
    memset(pNv12 + ySize, 128, ySize / 2);

    // Subtle gradient background
    for (uint32_t y = 0; y < height; y++) {
        uint8_t rowVal = static_cast<uint8_t>(20 + (y * 20 / height));
        for (uint32_t x = 0; x < width; x++) {
            pNv12[y * width + x] = rowVal;
        }
    }

    // Title banner: "REELCAM VIRTUAL CAMERA"
    DrawString(pNv12, width, (width / 2) - 180, (height / 2) - 30, "REELCAM VIRTUAL CAMERA", 235);
    // Subtitle: "LOAD A VIDEO FILE TO BEGIN"
    DrawString(pNv12, width, (width / 2) - 210, (height / 2) + 15, "LOAD A VIDEO FILE TO BEGIN", 160);
}

void VideoProcessor::ApplyHorizontalMirror(uint8_t* pNv12, uint32_t width, uint32_t height)
{
    // Flip Y plane row by row
    uint8_t* pY = pNv12;
    for (uint32_t y = 0; y < height; y++) {
        uint8_t* row = pY + y * width;
        for (uint32_t x = 0; x < width / 2; x++) {
            std::swap(row[x], row[width - 1 - x]);
        }
    }

    // Flip UV plane (pairs of U, V)
    uint8_t* pUV = pNv12 + width * height;
    uint32_t uvHeight = height / 2;
    uint32_t halfPairs = (width / 2) / 2;

    for (uint32_t y = 0; y < uvHeight; y++) {
        uint8_t* row = pUV + y * width;
        for (uint32_t p = 0; p < halfPairs; p++) {
            uint32_t leftIdx = p * 2;
            uint32_t rightIdx = (width / 2 - 1 - p) * 2;
            std::swap(row[leftIdx], row[rightIdx]);         // U
            std::swap(row[leftIdx + 1], row[rightIdx + 1]); // V
        }
    }
}

void VideoProcessor::ApplyWatermarkBadge(uint8_t* pNv12, uint32_t width, uint32_t height)
{
    // Badge location: Top-Right corner (x: width - 260, y: 30)
    uint32_t badgeX = (width > 300) ? (width - 260) : 10;
    uint32_t badgeY = 30;
    uint32_t badgeW = 230;
    uint32_t badgeH = 34;

    uint8_t* pY = pNv12;

    // Draw semi-transparent dark badge box
    for (uint32_t y = badgeY; y < badgeY + badgeH && y < height; y++) {
        for (uint32_t x = badgeX; x < badgeX + badgeW && x < width; x++) {
            // Darken background for high contrast
            pY[y * width + x] = static_cast<uint8_t>(pY[y * width + x] / 3);
        }
    }

    // Draw thin border around badge
    for (uint32_t x = badgeX; x < badgeX + badgeW && x < width; x++) {
        pY[badgeY * width + x] = 200;
        pY[(badgeY + badgeH - 1) * width + x] = 200;
    }
    for (uint32_t y = badgeY; y < badgeY + badgeH && y < height; y++) {
        pY[y * width + badgeX] = 200;
        pY[y * width + (badgeX + badgeW - 1)] = 200;
    }

    // Text inside badge: "[ REC ] PRE-RECORDED"
    DrawString(pY, width, badgeX + 12, badgeY + 10, "PRE-RECORDED", 240);
}

